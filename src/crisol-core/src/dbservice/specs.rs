//! What each data service is run with: its configuration, the one-time initializer and the
//! long-running service (`ProcessSpec`s), and the files that carry its password to it.
//!
//! No password is ever in an argument. The ways in, by service (ADR-0016):
//!
//! | Service | Initialization | Running | Clients Crisol runs |
//! |---|---|---|---|
//! | MySQL | `--init-file` (`ALTER USER`), deleted afterwards | the data has it | `mysqladmin --defaults-extra-file` |
//! | MariaDB | `--init-file` on the first launch, deleted once running | the data has it | `mysqladmin --defaults-extra-file` |
//! | PostgreSQL | `initdb --pwfile`, deleted afterwards | the data has it | `pg_ctl` and `pg_isready` need none |
//! | Redis | – | a private configuration file (`requirepass`) | `redis-cli` with `REDISCLI_AUTH` in its environment |
//! | Garnet | – | a private configuration file (`Password`) | none (the group ends) |
//! | Meilisearch | – | `MEILI_MASTER_KEY` in the environment | none |

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::time::Duration;

use super::{DbError, DbKind, DbPlan, Initializer};
use crate::process::ProcessSpec;
use crate::secrets::{self, Secret};
use crate::service::{HealthCheck, HealthCommand, LifecyclePolicy, ServiceSpec};

/// A path as it goes between the quotes of a `my.ini` value (forward slashes).
fn quote(path: &Path) -> Result<String, DbError> {
    let text = path.to_string_lossy().replace('\\', "/");
    if let Some(bad) = text
        .chars()
        .find(|c| matches!(c, '"' | '#' | ';') || c.is_control())
    {
        return Err(DbError::Unusable(format!(
            "`{text}` has a character the database configuration would read differently ({bad:?}); \
             use a Crisol home without it"
        )));
    }
    Ok(format!("\"{text}\""))
}

/// A path as it goes between the single quotes of a `postgresql.conf` value.
fn quote_pg(path: &Path) -> Result<String, DbError> {
    let text = path.to_string_lossy().replace('\\', "/");
    if let Some(bad) = text.chars().find(|c| *c == '\'' || c.is_control()) {
        return Err(DbError::Unusable(format!(
            "`{text}` has a character the database configuration would read differently ({bad:?}); \
             use a Crisol home without it"
        )));
    }
    Ok(format!("'{text}'"))
}

/// The text of `postgresql.conf`: this computer only, the port of `crisol.toml`, the log to
/// standard error (Crisol keeps it in `runtime.log`) and the user's own `*.conf`.
fn render_postgres(plan: &DbPlan) -> Result<String, DbError> {
    let mut text = String::from(
        "# Generated by Crisol; it is rewritten whenever the plan changes. Your own settings go in\n\
         # the `overrides` folder next to it, which is never touched.\n\n",
    );
    let mut line = |key: &str, value: &str| {
        text.push_str(key);
        text.push_str(" = ");
        text.push_str(value);
        text.push('\n');
    };
    // This computer only; the superuser has a generated password (`scram-sha-256`).
    line("listen_addresses", "'127.0.0.1'");
    line("port", &plan.port.to_string());
    line("log_destination", "'stderr'");
    line("logging_collector", "off");
    line("include_dir", &quote_pg(&plan.overrides)?);
    Ok(text)
}

/// The text of `my.ini` (`postgresql.conf` for PostgreSQL); empty for a service without one.
pub fn render_ini(plan: &DbPlan) -> Result<String, DbError> {
    if plan.kind.descriptor().config_file.is_none() {
        return Ok(String::new());
    }
    if plan.kind == DbKind::Postgres {
        return render_postgres(plan);
    }
    let mut text = String::from(
        "# Generated by Crisol; it is rewritten whenever the plan changes. Your own settings go in\n\
         # the `overrides` folder next to it, which is never touched.\n\n[mysqld]\n",
    );
    let mut line = |key: &str, value: &str| {
        text.push_str(key);
        text.push_str(" = ");
        text.push_str(value);
        text.push('\n');
    };
    line("basedir", &quote(&plan.version.path)?);
    line("datadir", &quote(&plan.data)?);
    line("port", &plan.port.to_string());
    // This computer only; root has a generated password.
    line("bind-address", "127.0.0.1");
    line("log-error", &quote(&plan.error_log)?);
    line("character-set-server", "utf8mb4");
    // `SELECT … INTO OUTFILE` and `LOAD_FILE` work in this folder and nowhere else: without it,
    // whoever can run SQL can write a file wherever the user can (a `.bat` in the Startup
    // folder, for one).
    line("secure_file_priv", &quote(&plan.files)?);
    if plan.kind == DbKind::Mysql {
        // The X protocol would open 33060 for nobody. (No `skip-name-resolve`: the only account
        // `--initialize-insecure` makes is `root@localhost`, and a connection from 127.0.0.1 is
        // that account only while the server maps the loopback address to `localhost`. Found
        // with the real MySQL 8.4.)
        line("mysqlx", "OFF");
    } else {
        // MariaDB makes `root@127.0.0.1` and `root@::1` as well.
        line("skip-name-resolve", "ON");
    }
    text.push_str("\n!includedir ");
    text.push_str(&quote(&plan.overrides)?);
    text.push('\n');
    Ok(text)
}

fn io_error(path: &Path) -> impl Fn(std::io::Error) -> DbError + '_ {
    move |e| DbError::Unusable(format!("{}: {e}", path.display()))
}

/// Writes `my.ini` (and the empty `overrides` folder it includes) if it changed.
pub fn write_ini(plan: &DbPlan) -> Result<(), DbError> {
    if plan.kind.descriptor().config_file.is_none() {
        return Ok(());
    }
    let text = render_ini(plan)?;
    fs::create_dir_all(&plan.overrides).map_err(io_error(&plan.overrides))?;
    if let Some(dir) = plan.ini.parent() {
        fs::create_dir_all(dir).map_err(io_error(dir))?;
    }
    if fs::read_to_string(&plan.ini).is_ok_and(|current| current == text) {
        return Ok(());
    }
    let tmp = plan.ini.with_extension("ini.new");
    fs::write(&tmp, text).map_err(io_error(&tmp))?;
    fs::rename(&tmp, &plan.ini).map_err(io_error(&plan.ini))
}

// ---- the files that carry a password -----------------------------------------------------

fn init_sql(plan: &DbPlan) -> PathBuf {
    plan.secret_path(".init.sql")
}

fn pwfile(plan: &DbPlan) -> PathBuf {
    plan.secret_path(".pwfile")
}

fn client_options(plan: &DbPlan) -> PathBuf {
    plan.secret_path(".client.cnf")
}

fn server_conf(plan: &DbPlan) -> PathBuf {
    plan.secret_path(".conf")
}

fn write_secret_file(file: &Path, text: &str) -> Result<(), DbError> {
    if let Some(dir) = file.parent() {
        fs::create_dir_all(dir).map_err(io_error(dir))?;
    }
    Ok(secrets::write_file(file, text)?)
}

/// Writes what the initializer is given to set the password: the SQL for MySQL and MariaDB
/// (`--init-file`), the password file for PostgreSQL. Nothing if there is no password.
pub fn write_init_files(plan: &DbPlan, secret: Option<&Secret>) -> Result<(), DbError> {
    let Some(secret) = secret else { return Ok(()) };
    let password = secret.expose();
    match plan.kind.descriptor().initializer {
        Initializer::Mysqld => write_secret_file(
            &init_sql(plan),
            &format!("ALTER USER 'root'@'localhost' IDENTIFIED BY '{password}';\n"),
        ),
        // The accounts MariaDB makes on Windows; one that does not exist is skipped.
        Initializer::MariadbInstall => write_secret_file(
            &init_sql(plan),
            &format!(
                "ALTER USER IF EXISTS 'root'@'localhost' IDENTIFIED BY '{password}';\n\
                 ALTER USER IF EXISTS 'root'@'127.0.0.1' IDENTIFIED BY '{password}';\n\
                 ALTER USER IF EXISTS 'root'@'::1' IDENTIFIED BY '{password}';\n"
            ),
        ),
        Initializer::Initdb => write_secret_file(&pwfile(plan), &format!("{password}\n")),
        Initializer::None => Ok(()),
    }
}

/// Deletes what [`write_init_files`] wrote. MariaDB's carries the password to its first launch,
/// so it stays unless `all` (the initialization failed or was cancelled).
pub fn remove_init_files(plan: &DbPlan, all: bool) {
    secrets::remove_file(&pwfile(plan));
    match plan.kind.descriptor().initializer {
        Initializer::Mysqld => secrets::remove_file(&init_sql(plan)),
        Initializer::MariadbInstall if all => secrets::remove_file(&init_sql(plan)),
        _ => {}
    }
}

/// MariaDB has taken its password from the first launch's file: delete it.
pub fn remove_first_launch_file(plan: &DbPlan) {
    if plan.kind.descriptor().initializer == Initializer::MariadbInstall {
        secrets::remove_file(&init_sql(plan));
    }
}

/// A path as it goes in a Redis configuration file.
fn quote_redis(path: &Path) -> Result<String, DbError> {
    let text = path.to_string_lossy().replace('\\', "/");
    if let Some(bad) = text
        .chars()
        .find(|c| matches!(c, '"' | '\'') || c.is_control())
    {
        return Err(DbError::Unusable(format!(
            "`{text}` has a character the Redis configuration would read differently ({bad:?}); \
             use a Crisol home without it"
        )));
    }
    Ok(format!("\"{text}\""))
}

/// Writes what the running service reads: the options file of `mysqladmin`, the configuration of
/// Redis and Garnet (where their password is), and the folder `secure_file_priv` points at. They
/// are in `secrets/` and are rewritten at every start.
pub fn write_runtime_files(plan: &DbPlan, secret: Option<&Secret>) -> Result<(), DbError> {
    match plan.kind {
        DbKind::Mysql | DbKind::Mariadb => {
            fs::create_dir_all(&plan.files).map_err(io_error(&plan.files))?;
            let mut text = String::from("[client]\nuser=root\nhost=127.0.0.1\nprotocol=tcp\n");
            let _ = writeln!(text, "port={}", plan.port);
            if let Some(secret) = secret {
                let _ = writeln!(text, "password=\"{}\"", secret.expose());
            }
            write_secret_file(&client_options(plan), &text)
        }
        DbKind::Redis => {
            let mut text = String::from("# Generated by Crisol; it holds the password.\n");
            let _ = write!(
                text,
                "bind 127.0.0.1\nport {}\nprotected-mode yes\nmaxmemory 512mb\n",
                plan.port
            );
            // Started without save points the Windows port saves nothing, not even on
            // `SHUTDOWN` (found with the real one).
            text.push_str("save 900 1\nsave 300 100\nsave 60 10000\n");
            let _ = writeln!(text, "dir {}", quote_redis(&plan.data)?);
            if let Some(secret) = secret {
                let _ = writeln!(text, "requirepass {}", secret.expose());
            }
            write_secret_file(&server_conf(plan), &text)
        }
        DbKind::Garnet => {
            let text = match secret {
                Some(secret) => format!(
                    "{{ \"AuthenticationMode\": \"Password\", \"Password\": \"{}\" }}\n",
                    secret.expose()
                ),
                None => "{ }\n".to_owned(),
            };
            write_secret_file(&server_conf(plan), &text)
        }
        DbKind::Postgres | DbKind::Mongodb | DbKind::Mailpit | DbKind::Meilisearch => Ok(()),
    }
}

// ---- processes ---------------------------------------------------------------------------

fn program(plan: &DbPlan, relative: &str) -> PathBuf {
    plan.version.path.join(relative)
}

/// The one-time initializer, writing into the staging folder.
#[must_use]
pub fn init_spec(plan: &DbPlan, secret: Option<&Secret>) -> ProcessSpec {
    let spec = match plan.kind.descriptor().initializer {
        // The superuser is `postgres`; with a password the server asks for it (`scram-sha-256`,
        // also from 127.0.0.1).
        Initializer::Initdb => {
            let spec = ProcessSpec::new(program(plan, "bin/initdb.exe"))
                .arg("-D")
                .arg(&plan.staging)
                .args(["-U", "postgres", "-E", "UTF8"]);
            if secret.is_some() {
                spec.args(["-A", "scram-sha-256"])
                    .arg(format!("--pwfile={}", pwfile(plan).display()))
            } else {
                spec.args(["-A", "trust"])
            }
        }
        // MariaDB makes a root without a password; the first launch sets it.
        Initializer::MariadbInstall => {
            ProcessSpec::new(program(plan, "bin/mariadb-install-db.exe"))
                .arg(format!("--datadir={}", plan.staging.display()))
        }
        _ => {
            let spec = ProcessSpec::new(program(plan, plan.kind.descriptor().server))
                .arg(format!("--defaults-file={}", plan.ini.display()))
                .arg("--initialize-insecure")
                .arg(format!("--datadir={}", plan.staging.display()))
                .arg("--console");
            if secret.is_some() {
                spec.arg(format!("--init-file={}", init_sql(plan).display()))
            } else {
                spec
            }
        }
    };
    spec.cwd(&plan.version.path).log_file(&plan.runtime_log)
}

/// The long-running service.
#[must_use]
pub fn service_spec(plan: &DbPlan, secret: Option<&Secret>) -> ServiceSpec {
    match plan.kind {
        DbKind::Mysql | DbKind::Mariadb => mysql_spec(plan, secret),
        DbKind::Postgres => postgres_spec(plan),
        _ => simple_spec(plan, secret),
    }
}

fn mysql_spec(plan: &DbPlan, secret: Option<&Secret>) -> ServiceSpec {
    let mut server = ProcessSpec::new(program(plan, plan.kind.descriptor().server))
        .arg(format!("--defaults-file={}", plan.ini.display()))
        .arg("--console");
    // MariaDB's first launch: the file that sets the password is there until it has been used.
    if plan.kind == DbKind::Mariadb && init_sql(plan).is_file() {
        server = server.arg(format!("--init-file={}", init_sql(plan).display()));
    }
    let admin = ProcessSpec::new(program(plan, "bin/mysqladmin.exe"));
    // The options file has the user, the host, the port and the password: nothing secret is in
    // the command line (it has to be the first option).
    let admin = if secret.is_some() {
        admin.arg(format!(
            "--defaults-extra-file={}",
            client_options(plan).display()
        ))
    } else {
        admin.args([
            "--protocol=tcp",
            "--host=127.0.0.1",
            &format!("--port={}", plan.port),
            "--user=root",
        ])
    }
    .arg("shutdown");
    ServiceSpec::new(plan.name())
        .process(server.cwd(&plan.version.path).log_file(&plan.runtime_log))
        .port(plan.port)
        .health(HealthCheck::Ports(vec![plan.port]))
        .graceful_stop(admin)
        .policy(LifecyclePolicy {
            // A first start, or one after a crash, replays the redo log.
            startup_timeout: Duration::from_secs(90),
            // A clean shutdown flushes the buffer pool.
            stop_grace: Duration::from_secs(30),
            ..LifecyclePolicy::default()
        })
}

fn postgres_spec(plan: &DbPlan) -> ServiceSpec {
    // `pg_ctl` and `pg_isready` talk to the postmaster through its files and its port, and need
    // no password.
    let stop = ProcessSpec::new(program(plan, "bin/pg_ctl.exe"))
        .arg("stop")
        .arg("-D")
        .arg(&plan.data)
        .args(["-m", "fast"]);
    let ready = ProcessSpec::new(program(plan, "bin/pg_isready.exe")).args([
        "-h",
        "127.0.0.1",
        "-p",
        &plan.port.to_string(),
        "-q",
    ]);
    ServiceSpec::new(plan.name())
        .process(
            ProcessSpec::new(program(plan, plan.kind.descriptor().server))
                .arg("-D")
                .arg(&plan.data)
                .arg("-c")
                .arg(format!("config_file={}", plan.ini.display()))
                .cwd(&plan.version.path)
                .log_file(&plan.runtime_log),
        )
        .port(plan.port)
        // The port opens before the server accepts connections; `pg_isready` says when it does.
        .health(HealthCheck::Command(HealthCommand {
            spec: ready,
            timeout: Duration::from_secs(5),
        }))
        .graceful_stop(stop)
        .policy(LifecyclePolicy {
            startup_timeout: Duration::from_secs(90),
            stop_grace: Duration::from_secs(30),
            ..LifecyclePolicy::default()
        })
}

/// MongoDB, Mailpit, Meilisearch, Redis and Garnet: one process, ready when its ports listen.
/// Redis has a shutdown command; the others have none Crisol can use, so a stop ends the group
/// (all of them recover their data from their own log or file at the next start).
fn simple_spec(plan: &DbPlan, secret: Option<&Secret>) -> ServiceSpec {
    let data = &plan.data;
    let mut process = ProcessSpec::new(program(plan, plan.kind.descriptor().server))
        .cwd(data)
        .log_file(&plan.runtime_log);
    match plan.kind {
        DbKind::Mongodb => {
            process = process.arg("--dbpath").arg(data).args([
                "--bind_ip",
                "127.0.0.1",
                "--port",
                &plan.port.to_string(),
            ]);
        }
        DbKind::Mailpit => {
            process = process
                .args(["--listen", &format!("127.0.0.1:{}", plan.port)])
                .args([
                    "--smtp",
                    &format!("127.0.0.1:{}", plan.extra_port.unwrap_or(1025)),
                ])
                .arg("--database")
                .arg(data.join("mailpit.db"))
                // Only the name Nginx serves it under: a page that makes the browser reach
                // `127.0.0.1:<port>` under another name (DNS rebinding) gets nothing.
                .args([
                    "--allowed-hosts",
                    plan.host.as_deref().unwrap_or("mail.test"),
                ])
                // Nothing leaves this computer, not even a look for a newer version.
                .arg("--disable-version-check");
        }
        DbKind::Meilisearch => {
            process = process
                .args(["--http-addr", &format!("127.0.0.1:{}", plan.port)])
                .arg("--db-path")
                .arg(data.join("db"))
                .arg("--dump-dir")
                .arg(data.join("dumps"))
                .arg("--snapshot-dir")
                .arg(data.join("snapshots"))
                // ADR-0004: no telemetry.
                .arg("--no-analytics");
            // The master key goes in the environment of the process, not in its arguments.
            if let Some(secret) = secret {
                process = process.env("MEILI_MASTER_KEY", secret.expose());
            }
        }
        DbKind::Redis => {
            // Everything, the password included, is in a private configuration file.
            process = process.arg(server_conf(plan));
        }
        DbKind::Garnet => {
            // Garnet keeps its keys in memory unless it is told to persist (checkpoints/AOF):
            // a cache is what it is used for here. It sends no telemetry.
            process = process
                .args(["--bind", "127.0.0.1", "--port", &plan.port.to_string()])
                .arg("--config-import-path")
                .arg(server_conf(plan))
                .arg("--checkpointdir")
                .arg(data.join("checkpoints"))
                // Lua is off by default, and Laravel's queues use it.
                .arg("--lua");
        }
        DbKind::Mysql | DbKind::Mariadb | DbKind::Postgres => {}
    }
    let ports: Vec<u16> = std::iter::once(plan.port).chain(plan.extra_port).collect();
    let mut spec = ServiceSpec::new(plan.name())
        .process(process)
        .health(HealthCheck::Ports(ports.clone()))
        .policy(LifecyclePolicy {
            startup_timeout: Duration::from_secs(60),
            ..LifecyclePolicy::default()
        });
    for port in ports {
        spec = spec.port(port);
    }
    if plan.kind == DbKind::Redis {
        // `SHUTDOWN` saves the data if there are save points, then leaves. The password goes in
        // the environment variable `redis-cli` reads for it, not in its arguments.
        let mut stop = ProcessSpec::new(program(plan, "redis-cli.exe")).args([
            "-h",
            "127.0.0.1",
            "-p",
            &plan.port.to_string(),
            "shutdown",
        ]);
        if let Some(secret) = secret {
            stop = stop.env("REDISCLI_AUTH", secret.expose());
        }
        spec = spec.graceful_stop(stop);
    }
    spec
}

// ---- credentials for the project's .env ---------------------------------------------------

/// What a project needs to connect, as `.env` lines and notes for the person.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Credentials {
    /// `KEY=value` lines for the project's `.env`.
    pub lines: Vec<(String, String)>,
    /// Things to know (a database made before passwords existed, …).
    pub notes: Vec<String>,
}

/// The `.env` lines for connecting to `plan`'s service with `secret`.
#[must_use]
pub fn credentials(plan: &DbPlan, secret: Option<&Secret>) -> Credentials {
    let pair = |k: &str, v: &str| (k.to_owned(), v.to_owned());
    let port = plan.port.to_string();
    let password = secret.map(|s| s.expose().to_owned());
    let mut lines = Vec::new();
    let mut notes = Vec::new();
    match plan.kind {
        DbKind::Mysql | DbKind::Mariadb | DbKind::Postgres => {
            let (connection, user) = match plan.kind {
                DbKind::Mysql => ("mysql", "root"),
                DbKind::Mariadb => ("mariadb", "root"),
                _ => ("pgsql", "postgres"),
            };
            lines.push(pair("DB_CONNECTION", connection));
            lines.push(pair("DB_HOST", "127.0.0.1"));
            lines.push(pair("DB_PORT", &port));
            lines.push(pair("DB_USERNAME", user));
            lines.push(pair("DB_PASSWORD", password.as_deref().unwrap_or("")));
        }
        DbKind::Redis | DbKind::Garnet => {
            lines.push(pair("REDIS_HOST", "127.0.0.1"));
            lines.push(pair("REDIS_PORT", &port));
            lines.push(pair(
                "REDIS_PASSWORD",
                password.as_deref().unwrap_or("null"),
            ));
        }
        DbKind::Meilisearch => {
            lines.push(pair(
                "MEILISEARCH_HOST",
                &format!("http://127.0.0.1:{port}"),
            ));
            lines.push(pair("MEILISEARCH_KEY", password.as_deref().unwrap_or("")));
        }
        DbKind::Mailpit => {
            lines.push(pair("MAIL_MAILER", "smtp"));
            lines.push(pair("MAIL_HOST", "127.0.0.1"));
            lines.push(pair(
                "MAIL_PORT",
                &plan
                    .extra_port
                    .map_or_else(|| "1025".to_owned(), |p| p.to_string()),
            ));
            lines.push(pair("MAIL_USERNAME", "null"));
            lines.push(pair("MAIL_PASSWORD", "null"));
            notes.push(format!(
                "Mailpit has no password for SMTP. Read the mail at http://{}/ (Nginx serves it under that name; Mailpit answers to no other).",
                plan.host.as_deref().unwrap_or("mail.test")
            ));
        }
        DbKind::Mongodb => {
            lines.push(pair("MONGODB_HOST", "127.0.0.1"));
            lines.push(pair("MONGODB_PORT", &port));
        }
    }
    if password.is_none() && matches!(plan.kind.auth(), super::Auth::Stored | super::Auth::Applied)
    {
        notes.push(format!(
            "this {} was made before Crisol generated passwords and has none. To give it one, \
             stop it, delete {} and start it again: that makes it new (the data in it is lost).",
            plan.kind.service(),
            plan.data.display()
        ));
    }
    Credentials { lines, notes }
}
